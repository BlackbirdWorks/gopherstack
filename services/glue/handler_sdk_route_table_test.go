// sdkRouteCases is the authoritative X-Amz-Target for every real Glue
// operation, extracted from glue@v1.152.0 serializers.go: each op's
// awsAwsjson11_serializeOp<Op>.HandleSerialize sets
// httpBindingEncoder.SetHeader("X-Amz-Target").String("AWSGlue.<Op>") and
// always request.Request.Method = "POST" against path "/" -- Glue is
// JSON-RPC 1.1 (services/_PROTOCOLS.md), so unlike a REST-family service
// there is no path template to get wrong: dispatch is entirely by this one
// header. ExtractOperation and Handler() both derive the action the same
// way (TrimPrefix on "AWSGlue."), so the class of bug this table can catch
// is a dispatch-table key that doesn't exactly match the real op name
// (typo, wrong case -- Glue is case-sensitive JSON-RPC), not a
// route-template mismatch.
//
// This table covers all 299 real Glue ops, which is also gopherstack's
// full implemented set (h.GetSupportedOperations(), 299/299) as of
// glue@v1.152.0 -- confirmed by diffing glueOpBindings (the single
