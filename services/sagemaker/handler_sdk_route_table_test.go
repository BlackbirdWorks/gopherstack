// sdkRouteCases is the authoritative X-Amz-Target for every real SageMaker
// operation, extracted from sagemaker@v1.263.2 serializers.go: each op's
// awsAwsjson11_serializeOp<Op>.HandleSerialize sets
// httpBindingEncoder.SetHeader("X-Amz-Target").String("SageMaker.<Op>") and
// always request.Request.Method = "POST" against path "/" -- SageMaker is
// JSON-RPC 1.1 (services/_PROTOCOLS.md), so unlike a REST-family service
// there is no path template to get wrong: dispatch is entirely by this one
// header. ExtractOperation and Handler() both derive the action the same
// way (TrimPrefix on "SageMaker."), so the class of bug this table can
// catch is a dispatch-table key that doesn't exactly match the real op name
// (typo, wrong case -- SageMaker is case-sensitive JSON-RPC), not a
// route-template mismatch.
//
// This table covers all 403 real SageMaker ops, which is also gopherstack's
// full implemented set (h.GetSupportedOperations(), 403/403) as of
// sagemaker@v1.263.2 -- confirmed by diffing GetSupportedOperations()
// against this exact list, zero mismatches either direction. Unlike glue's
// or cognitoidp's dispatch table, SageMaker's dispatch is a chain of
// per-family switch statements rather than a single map, so it was also
// spot-checked for "case" labels with no corresponding SDK op; the only hit
// was a false positive ("RoleArn" in an unrelated field-decoding switch in
// handler_monitoring_job_definitions.go), not a stray operation case.
//
// Regenerate by grepping serializers.go for every
