func (b *InMemoryBackend) newDistribution(drg *Drg, name, typ string, st DrgStatement) *DrgRouteDistribution {
	st.ID = newOCID(kindDrgStatement)

	d := &DrgRouteDistribution{
		Base: b.newBase(kindDrgDist, drg.CompartmentID, name, TagsIn{}), DrgID: drg.ID, DistributionType: typ,
		Statements: []DrgStatement{st},
	}
	b.add(d)

	return d
}

func (b *InMemoryBackend) newDrgTable(drg *Drg, name, importID string) *DrgRouteTable {
	t := &DrgRouteTable{
		Base: b.newBase(kindDrgRouteTable, drg.CompartmentID, name, TagsIn{}), DrgID: drg.ID,
		ImportDrgRouteDistributionID: importID,
	}
	b.add(t)

	return t
}

// CreateDrg creates a DRG with its default route tables and route distributions.
func (b *InMemoryBackend) CreateDrg(in CreateDrgIn) (Resource, string, *APIError) {
	if aerr := b.checkCompartment(in.CompartmentID); aerr != nil {
		return nil, "", aerr
	}

	if aerr := validName(in.DisplayName); aerr != nil {
		return nil, "", aerr
	}

	if len(liveOf(b, func(*Drg) bool { return true })) >= maxDrgs {
		return nil, "", errLimit("The tenancy DRG limit (5) has been reached")
	}

	drg := &Drg{Base: b.newBase(kindDRG, in.CompartmentID, in.DisplayName, in.TagsIn)}
	all := DrgMatchCriteria{MatchType: matchAll}
	vcnOnly := DrgMatchCriteria{MatchType: matchType, AttachmentType: attVcn}

	export := b.newDistribution(drg, nameDefaultExport, distExport,
		DrgStatement{Action: actionAccept, Priority: 1, MatchCriteria: []DrgMatchCriteria{all}})
	importAll := b.newDistribution(drg, nameVcnImport, distImport,
		DrgStatement{Action: actionAccept, Priority: 1, MatchCriteria: []DrgMatchCriteria{all}})
	importVcn := b.newDistribution(drg, nameOtherImport, distImport,
		DrgStatement{Action: actionAccept, Priority: 1, MatchCriteria: []DrgMatchCriteria{vcnOnly}})
	vcnTable := b.newDrgTable(drg, nameVcnTable, importAll.ID)
	otherTable := b.newDrgTable(drg, nameOtherTable, importVcn.ID)

	drg.DefaultExportDrgRouteDistributionID = export.ID
	drg.DefaultDrgRouteTables = &DefaultDrgRouteTables{
		Vcn:                     vcnTable.ID,
		IpsecTunnel:             otherTable.ID,
		VirtualCircuit:          otherTable.ID,
		RemotePeeringConnection: otherTable.ID,
	}
	b.add(drg)

	return drg.view(), drg.Internal.Etag, nil
}

// UpdateDrgIn is the UpdateDrg request body.
type UpdateDrgIn struct {
	DefaultDrgRouteTables *DefaultDrgRouteTables `json:"defaultDrgRouteTables"`
	UpdateIn
}

// UpdateDrg changes a DRG's name, tags and default route tables.
func (b *InMemoryBackend) UpdateDrg(id, ifMatch string, in UpdateDrgIn) (Resource, string, *APIError) {
	return updateWith(b, id, ifMatch, in.UpdateIn, func(d *Drg) *APIError {
		if in.DefaultDrgRouteTables == nil {
			return nil
		}

		next := *d.DefaultDrgRouteTables

		for _, set := range []struct {
			dst *string
			src string
		}{
			{&next.Vcn, in.DefaultDrgRouteTables.Vcn},
			{&next.IpsecTunnel, in.DefaultDrgRouteTables.IpsecTunnel},
			{&next.VirtualCircuit, in.DefaultDrgRouteTables.VirtualCircuit},
			{&next.RemotePeeringConnection, in.DefaultDrgRouteTables.RemotePeeringConnection},
		} {
			if set.src == "" {
				continue
			}

			if aerr := b.drgChild(set.src, d.ID, kindDrgRouteTable); aerr != nil {
				return aerr
			}

			*set.dst = set.src
		}

		d.DefaultDrgRouteTables = &next

		return nil
	})
}

// drgChild checks that id names a live DRG route table or distribution that belongs to the DRG.
func (b *InMemoryBackend) drgChild(id, drgID, kind string) *APIError {
	switch kind {
	case kindDrgRouteTable:
		t, aerr := getLive[*DrgRouteTable](b, id)
		if aerr != nil {
			return aerr
		}

		if t.DrgID != drgID {
			return errParam("The DRG route table " + id + " belongs to a different DRG")
		}
	default:
		d, aerr := getLive[*DrgRouteDistribution](b, id)
		if aerr != nil {
			return aerr
		}

		if d.DrgID != drgID {
			return errParam("The DRG route distribution " + id + " belongs to a different DRG")
		}
	}

	return nil
}

// ChangeDrgCompartment moves a DRG; its route tables, distributions and attachments always follow it.
func (b *InMemoryBackend) ChangeDrgCompartment(id, compartment, ifMatch string) *APIError {
	if aerr := changeCompartment[*Drg](b, id, compartment, ifMatch); aerr != nil {
		return aerr
	}

	b.mu.Lock("ChangeDrgCompartment")
	defer b.mu.Unlock()

	for _, r := range b.res {
		switch v := r.(type) {
		case *DrgRouteTable:
			if v.DrgID == id {
				v.CompartmentID = compartment
			}
		case *DrgRouteDistribution:
			if v.DrgID == id {
				v.CompartmentID = compartment
			}
		case *DrgAttachment:
			if v.DrgID == id {
				v.CompartmentID = compartment
			}
		}
	}

	return nil
}

func (b *InMemoryBackend) deleteDrgCheck(id string) *APIError {
	if a := firstID(b.drgAttachments(id)); a != "" {
		return errConflict("The DRG " + id + " cannot be deleted because it still has attachment " + a)
	}

	return nil
}

// terminateDrg ends the route tables and distributions that belong to a DRG.
func (b *InMemoryBackend) terminateDrg(id string) {
	for _, r := range b.res {
		if !live(r) {
			continue
		}

		switch v := r.(type) {
		case *DrgRouteTable:
			if v.DrgID == id {
				b.markTerminating(v)
			}
		case *DrgRouteDistribution:
			if v.DrgID == id {
				b.markTerminating(v)
			}
		}
	}
}

func (b *InMemoryBackend) deleteDrgTableCheck(t *DrgRouteTable) *APIError {
	if d, ok := b.res[t.DrgID].(*Drg); ok && live(d) && d.DefaultDrgRouteTables != nil &&
		slices.Contains(d.DefaultDrgRouteTables.ids(), t.ID) {
		return errConflict("The default DRG route table " + t.ID + " of a DRG cannot be deleted")
	}

	return usedBy("DRG route table", t.ID, firstID(liveOf(b, func(a *DrgAttachment) bool {
		return a.DrgRouteTableID == t.ID
	})))
}

func (b *InMemoryBackend) deleteDrgDistCheck(d *DrgRouteDistribution) *APIError {
	if drg, ok := b.res[d.DrgID].(*Drg); ok && live(drg) && drg.DefaultExportDrgRouteDistributionID == d.ID {
		return errConflict("The default export route distribution " + d.ID + " of a DRG cannot be deleted")
	}

	user := firstID(liveOf(b, func(t *DrgRouteTable) bool { return t.ImportDrgRouteDistributionID == d.ID }))
	if user == "" {
		user = firstID(liveOf(b, func(a *DrgAttachment) bool { return a.ExportDrgRouteDistributionID == d.ID }))
	}

	return usedBy("DRG route distribution", d.ID, user)
}

// vcnDrgAttachment returns the live attachment of a VCN, if any.
func (b *InMemoryBackend) vcnDrgAttachment(vcnID string) *DrgAttachment {
	for _, a := range liveOf(b, func(a *DrgAttachment) bool { return a.VcnID == vcnID }) {
		return a
	}

	return nil
}

// checkDrgTarget validates a VCN route rule that targets a DRG: the DRG must be attached to that VCN.
func (b *InMemoryBackend) checkDrgTarget(id, vcnID string) *APIError {
	if _, aerr := getLive[*Drg](b, id); aerr != nil {
		return aerr
	}

	if !slices.ContainsFunc(b.drgAttachments(id), func(a *DrgAttachment) bool { return a.VcnID == vcnID }) {
		return errParam("The DRG " + id + " is not attached to the VCN " + vcnID)
	}

	return nil
}

// drgRouteTargeted reports whether a route table of the VCN still sends traffic to the DRG.
func (b *InMemoryBackend) drgRouteTargeted(drgID, vcnID string) string {
	return firstID(liveOf(b, func(rt *RouteTable) bool { return rt.VcnID == vcnID && routesTo(drgID)(rt) }))
}

// CreateDrgAttachmentIn is the CreateDrgAttachment request body.
type CreateDrgAttachmentIn struct {
	TagsIn
	NetworkDetails                    *DrgNetworkDetails `json:"networkDetails"`
	DoesPreserveOriginalRoutesWithNat *bool              `json:"doesPreserveOriginalRoutesWithNat"`
	DisplayName                       string             `json:"displayName"`
	DrgID                             string             `json:"drgId"`
	DrgRouteTableID                   string             `json:"drgRouteTableId"`
	RouteTableID                      string             `json:"routeTableId"`
	VcnID                             string             `json:"vcnId"`
	DrgNatPolicyID                    string             `json:"drgNatPolicyId"`
}

func (b *InMemoryBackend) vcnNetwork(in CreateDrgAttachmentIn) (*DrgNetworkDetails, *APIError) {
	nd := DrgNetworkDetails{Type: attVcn, ID: in.VcnID, RouteTableID: in.RouteTableID, VcnRouteType: vcnRouteCidrs}

	if in.NetworkDetails != nil {
		if in.NetworkDetails.Type != attVcn {
			return nil, errParam(
				"networkDetails.type must be VCN: other attachment types are created by their own service",
			)
		}

		nd = *in.NetworkDetails
		if nd.VcnRouteType == "" {
			nd.VcnRouteType = vcnRouteCidrs
		}

		if in.VcnID != "" && in.VcnID != nd.ID {
			return nil, errParam("vcnId and networkDetails.id name different VCNs")
		}
	}

	if nd.ID == "" {
		return nil, errMissing("vcnId or networkDetails.id is required")
	}

	if nd.VcnRouteType != vcnRouteCidrs && nd.VcnRouteType != vcnRouteSubnets {
		return nil, errParam("vcnRouteType must be VCN_CIDRS or SUBNET_CIDRS")
	}

	return &nd, nil
}

// CreateDrgAttachment attaches a VCN to a DRG; each VCN attaches to at most one DRG.
func (b *InMemoryBackend) CreateDrgAttachment(in CreateDrgAttachmentIn) (Resource, string, *APIError) {
	if in.DrgID == "" {
		return nil, "", errMissing("drgId is required")
	}

	if aerr := validName(in.DisplayName); aerr != nil {
		return nil, "", aerr
	}

	if in.DrgNatPolicyID != "" {
		return nil, "", errNotFound(in.DrgNatPolicyID)
	}

	if flag(in.DoesPreserveOriginalRoutesWithNat) {
		return nil, "", errParam("doesPreserveOriginalRoutesWithNat requires a drgNatPolicyId")
	}

	drg, aerr := getLive[*Drg](b, in.DrgID)
	if aerr != nil {
		return nil, "", aerr
	}

	nd, aerr := b.vcnNetwork(in)
	if aerr != nil {
		return nil, "", aerr
	}

	vcn, aerr := getLive[*Vcn](b, nd.ID)
	if aerr != nil {
		return nil, "", aerr
	}

	if cur := b.vcnDrgAttachment(vcn.ID); cur != nil {
		return nil, "", errConflict("The VCN " + vcn.ID + " is already attached to DRG " + cur.DrgID)
	}

	if aerr = b.attachmentRefs(nd, vcn.ID); aerr != nil {
		return nil, "", aerr
	}

	tableID := cmpOrStr(in.DrgRouteTableID, drg.DefaultDrgRouteTables.Vcn)
	if aerr = b.drgChild(tableID, drg.ID, kindDrgRouteTable); aerr != nil {
		return nil, "", aerr
	}

	a := &DrgAttachment{
		Base: b.newBase(kindDrgAttachment, drg.CompartmentID, in.DisplayName, in.TagsIn), DrgID: drg.ID,
		DrgRouteTableID: tableID, NetworkDetails: nd, VcnID: vcn.ID, RouteTableID: nd.RouteTableID,
	}
	b.moveTo(a, statAttaching, statAttached)
	b.add(a)

	return a.view(), a.Internal.Etag, nil
}

func (b *InMemoryBackend) attachmentRefs(nd *DrgNetworkDetails, vcnID string) *APIError {
	if nd.RouteTableID == "" {
		return nil
	}

	return refInVcn[*RouteTable](b, nd.RouteTableID, vcnID, "route table")
}

// UpdateDrgAttachmentIn is the UpdateDrgAttachment request body.
type UpdateDrgAttachmentIn struct {
	NetworkDetails                    *DrgNetworkDetails `json:"networkDetails"`
	DoesPreserveOriginalRoutesWithNat *bool              `json:"doesPreserveOriginalRoutesWithNat"`
	DrgRouteTableID                   *string            `json:"drgRouteTableId"`
	ExportDrgRouteDistributionID      *string            `json:"exportDrgRouteDistributionId"`
	RouteTableID                      *string            `json:"routeTableId"`
	DrgNatPolicyID                    *string            `json:"drgNatPolicyId"`
	UpdateIn
}

// UpdateDrgAttachment changes an attachment's name, tags, DRG route table, export distribution and VCN route settings.
func (b *InMemoryBackend) UpdateDrgAttachment(
	id, ifMatch string,
	in UpdateDrgAttachmentIn,
) (Resource, string, *APIError) {
	return updateWith(b, id, ifMatch, in.UpdateIn, func(a *DrgAttachment) *APIError {
		if a.LifecycleState != statAttached && a.LifecycleState != statAttaching {
			return errState("The DRG attachment " + a.ID + " is " + a.LifecycleState)
		}

		if in.DrgNatPolicyID != nil && *in.DrgNatPolicyID != "" {
			return errNotFound(*in.DrgNatPolicyID)
		}

		if flag(in.DoesPreserveOriginalRoutesWithNat) {
			return errParam("doesPreserveOriginalRoutesWithNat requires a drgNatPolicyId")
		}

		next := *a

		if aerr := b.applyAttachmentUpdate(&next, in); aerr != nil {
			return aerr
		}

		a.DrgRouteTableID, a.ExportDrgRouteDistributionID = next.DrgRouteTableID, next.ExportDrgRouteDistributionID
		a.RouteTableID, a.NetworkDetails = next.RouteTableID, next.NetworkDetails

		return nil
	})
}

func (b *InMemoryBackend) applyAttachmentUpdate(a *DrgAttachment, in UpdateDrgAttachmentIn) *APIError {
	if in.DrgRouteTableID != nil {
		if aerr := b.drgChild(*in.DrgRouteTableID, a.DrgID, kindDrgRouteTable); aerr != nil {
			return aerr
		}

		a.DrgRouteTableID = *in.DrgRouteTableID
	}

	if in.ExportDrgRouteDistributionID != nil && *in.ExportDrgRouteDistributionID != "" {
		if aerr := b.setExportDistribution(a, *in.ExportDrgRouteDistributionID); aerr != nil {
			return aerr
		}
	}

	if a.NetworkDetails == nil || a.NetworkDetails.Type != attVcn {
		return nil
	}

	return b.applyVcnNetworkUpdate(a, in)
}

func (b *InMemoryBackend) setExportDistribution(a *DrgAttachment, id string) *APIError {
	if attachmentType(a) == attVcn {
		return errParam("Routes cannot be exported through a VCN attachment")
	}

	d, aerr := getLive[*DrgRouteDistribution](b, id)
	if aerr != nil {
		return aerr
	}

	if d.DrgID != a.DrgID || d.DistributionType != distExport {
		return errParam("exportDrgRouteDistributionId must name an export distribution of the same DRG")
	}

	a.ExportDrgRouteDistributionID = d.ID

	return nil
}

func (b *InMemoryBackend) applyVcnNetworkUpdate(a *DrgAttachment, in UpdateDrgAttachmentIn) *APIError {
	nd := *a.NetworkDetails

	if in.RouteTableID != nil {
		nd.RouteTableID = *in.RouteTableID
	}

	if in.NetworkDetails != nil {
		nd.RouteTableID = cmpOrStr(in.NetworkDetails.RouteTableID, nd.RouteTableID)
		nd.VcnRouteType = cmpOrStr(in.NetworkDetails.VcnRouteType, nd.VcnRouteType)
	}

	if nd.VcnRouteType != vcnRouteCidrs && nd.VcnRouteType != vcnRouteSubnets {
		return errParam("vcnRouteType must be VCN_CIDRS or SUBNET_CIDRS")
	}

	if aerr := b.attachmentRefs(&nd, a.VcnID); aerr != nil {
		return aerr
	}

	a.NetworkDetails, a.RouteTableID = &nd, nd.RouteTableID

	return nil
}

// DeleteDrgAttachment detaches a DRG attachment.
func (b *InMemoryBackend) DeleteDrgAttachment(id, ifMatch string) *APIError {
	b.mu.Lock("DeleteDrgAttachment")
	defer b.mu.Unlock()

	a, aerr := get[*DrgAttachment](b, id)
	if aerr != nil {
		return aerr
	}

	if !live(a) {
		return nil
	}

	if aerr = checkEtag(a, ifMatch); aerr != nil {
		return aerr
	}

	if a.VcnID != "" {
		if rt := b.drgRouteTargeted(a.DrgID, a.VcnID); rt != "" {
			return errConflict("The DRG attachment " + id + " cannot be deleted while route table " + rt +
				" has a rule targeting the DRG")
		}
	}

	b.moveTo(a, statDetaching, statDetached)

	return nil
}

// DrgNetworkIn describes a non-VCN attachment registered by the service that owns the network
// (an IPSec connection, virtual circuit or remote peering connection).
type DrgNetworkIn struct {
	DrgID       string
	Type        string
	NetworkID   string
	DisplayName string
}

// AttachDrgNetwork registers an IPSec tunnel, virtual circuit or remote peering connection with a DRG.
func (b *InMemoryBackend) AttachDrgNetwork(in DrgNetworkIn) (string, error) {
	b.mu.Lock("AttachDrgNetwork")
	defer b.mu.Unlock()

	if !slices.Contains([]string{attIpsec, attVC, attRPC}, in.Type) {
		return "", errParam("type must be IPSEC_TUNNEL, VIRTUAL_CIRCUIT or REMOTE_PEERING_CONNECTION")
	}

	drg, aerr := getLive[*Drg](b, in.DrgID)
	if aerr != nil {
		return "", aerr
	}

	a := &DrgAttachment{
		Base:  b.newBase(kindDrgAttachment, drg.CompartmentID, in.DisplayName, TagsIn{}),
		DrgID: drg.ID, DrgRouteTableID: drg.DefaultDrgRouteTables.forType(in.Type),
		ExportDrgRouteDistributionID: drg.DefaultExportDrgRouteDistributionID,
		NetworkDetails:               &DrgNetworkDetails{Type: in.Type, ID: in.NetworkID},
	}
	b.moveTo(a, statAttaching, statAttached)
	b.add(a)

	return a.ID, nil
}

// DetachDrgNetwork removes an attachment registered by AttachDrgNetwork; unknown ids are ignored.
func (b *InMemoryBackend) DetachDrgNetwork(attachmentID string) {
	b.mu.Lock("DetachDrgNetwork")
	defer b.mu.Unlock()

	if a, ok := b.res[attachmentID].(*DrgAttachment); ok && live(a) {
		b.moveTo(a, statDetaching, statDetached)
	}
}

const (
	redundancyNone        = "NOT_REDUNDANT_NO_CONNECTION"
	redundancySingleIpsec = "NOT_REDUNDANT_SINGLE_IPSEC"
	redundancySingleVC    = "NOT_REDUNDANT_SINGLE_VIRTUALCIRCUIT"
	redundancyMultiIpsec  = "NOT_REDUNDANT_MULTIPLE_IPSECS"
	redundancyMultiVC     = "NOT_REDUNDANT_MULTIPLE_VIRTUALCIRCUITS"
	redundancyMixed       = "NOT_REDUNDANT_MIX_CONNECTIONS"
	redundancyNA          = "NOT_AVAILABLE"
)

// DrgRedundancy is the GetDrgRedundancyStatus response.
type DrgRedundancy struct {
	ID     string `json:"id"`
	Status string `json:"status"`
}

// GetDrgRedundancyStatus derives the redundancy of a DRG from its live IPSec and virtual circuit attachments.
func (b *InMemoryBackend) GetDrgRedundancyStatus(id string) (DrgRedundancy, *APIError) {
	b.mu.RLock("GetDrgRedundancyStatus")
	defer b.mu.RUnlock()

	d, aerr := get[*Drg](b, id)
	if aerr != nil {
		return DrgRedundancy{}, aerr
	}

	if !live(d) || d.LifecycleState != statAvailable {
		return DrgRedundancy{ID: id, Status: redundancyNA}, nil
	}

	var ipsec, vc int

	for _, a := range b.drgAttachments(id) {
		switch attachmentType(a) {
		case attIpsec:
			ipsec++
		case attVC:
			vc++
		}
	}

	return DrgRedundancy{ID: id, Status: redundancyOf(ipsec, vc)}, nil
}

func redundancyOf(ipsec, vc int) string {
	switch {
	case ipsec == 0 && vc == 0:
		return redundancyNone
	case ipsec > 0 && vc > 0:
		return redundancyMixed
	case ipsec == 1:
		return redundancySingleIpsec
	case vc == 1:
		return redundancySingleVC
	case ipsec > 1:
		return redundancyMultiIpsec
	}

	return redundancyMultiVC
}

// DrgUpgradeStatus is the GetUpgradeStatus response.
type DrgUpgradeStatus struct {
	DrgID               string `json:"drgId"`
	Status              string `json:"status"`
	UpgradedConnections string `json:"upgradedConnections"`
}

// GetUpgradeStatus reports the DRG upgrade status; every DRG created here is already upgraded.
func (b *InMemoryBackend) GetUpgradeStatus(id string) (DrgUpgradeStatus, *APIError) {
	b.mu.RLock("GetUpgradeStatus")
	defer b.mu.RUnlock()

	if _, aerr := get[*Drg](b, id); aerr != nil {
		return DrgUpgradeStatus{}, aerr
	}

	return DrgUpgradeStatus{
		DrgID: id, Status: "UPGRADED", UpgradedConnections: strconv.Itoa(len(b.drgAttachments(id))),
	}, nil
}

// UpgradeDrg refuses to upgrade a DRG that already has per-attachment route tables.
func (b *InMemoryBackend) UpgradeDrg(id string) (string, *APIError) {
	b.mu.Lock("UpgradeDrg")
	defer b.mu.Unlock()

	d, aerr := getLive[*Drg](b, id)
	if aerr != nil {
		return "", aerr
	}

	return "", errState("The DRG " + d.ID + " is already upgraded")
}

