func TestSAMTransform_MixedFeaturesDeploy(t *testing.T) {
	t.Parallel()

	env := newSAMEventEnv(t)
	deploySAM(t, env.client, samMixedFeaturesTemplate)

	want := map[string]string{
		"FnAliaslive":                     "AWS::Lambda::Alias",
		"ServerlessDeploymentApplication": "AWS::CodeDeploy::Application",
		"CodeDeployServiceRole":           "AWS::IAM::Role",
		"FnDeploymentGroup":               "AWS::CodeDeploy::DeploymentGroup",
		"FnLogs":                          "AWS::Logs::SubscriptionFilter",
		"FnLogsPermission":                "AWS::Lambda::Permission",
		"FnIot":                           "AWS::IoT::TopicRule",
		"FnIotPermission":                 "AWS::Lambda::Permission",
		"FnSns":                           "AWS::SNS::Subscription",
		"FnSnsQueue":                      "AWS::SQS::Queue",
		"FnSnsQueuePolicy":                "AWS::SQS::QueuePolicy",
		"FnSnsEventSourceMapping":         "AWS::Lambda::EventSourceMapping",
		"FnCognitoPermission":             "AWS::Lambda::Permission",
		"FnAlexaPermission":               "AWS::Lambda::Permission",
		"FnTick":                          "AWS::Events::Rule",
		"FnTickQueue":                     "AWS::SQS::Queue",
		"FnTickQueuePolicy":               "AWS::SQS::QueuePolicy",
		"ApiUsagePlan":                    "AWS::ApiGateway::UsagePlan",
		"ApiApiKey":                       "AWS::ApiGateway::ApiKey",
		"ApiUsagePlanKey":                 "AWS::ApiGateway::UsagePlanKey",
	}
	ids := logicalIDs(t, env.client)
	for id, typ := range want {
		assert.Equal(t, typ, ids[id], id)
	}
	assert.Equal(t, "AWS::ApiGateway::BasePathMapping", ids["ApishopBasePathMapping"])

	pool := getTemplate(t, env.client, types.TemplateStageProcessed)
	assert.Contains(t, pool, "PreSignUp")

	assertDeleteClean(t, env.client)
}
