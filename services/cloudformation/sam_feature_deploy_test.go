const samKafkaDocDBTemplate = samHeader + `
Resources:
  Fn:
    Type: AWS::Serverless::Function
    Properties:
` + samFnHeader + `
      Policies:
        - S3ReadPolicy:
            BucketName: my-bucket
        - AmazonSQSFullAccess
      Events:
        Kafka:
          Type: SelfManagedKafka
          Properties:
            KafkaBootstrapServers: [broker1:9092, broker2:9092]
            Topics: [orders]
            ConsumerGroupId: group-1
            BatchSize: 50
            SourceAccessConfigurations:
              - Type: VPC_SUBNET
                URI: subnet-0a1b2c3d
              - Type: VPC_SECURITY_GROUP
                URI: sg-0a1b2c3d
              - Type: BASIC_AUTH
                URI: arn:aws:secretsmanager:us-east-1:000000000000:secret:kafka-AbCdEf
            FilterCriteria:
              Filters:
                - Pattern: '{"value": {"status": ["new"]}}'
        Docs:
          Type: DocumentDB
          Properties:
            Cluster: arn:aws:rds:us-east-1:000000000000:cluster:docdb-1
            DatabaseName: shop
            CollectionName: orders
            FullDocument: UpdateLookup
            StartingPosition: LATEST
            SourceAccessConfigurations:
              - Type: BASIC_AUTH
                URI: arn:aws:secretsmanager:us-east-1:000000000000:secret:docdb-AbCdEf
`

func TestSAMTransform_KafkaAndDocumentDBMappings(t *testing.T) {
	t.Parallel()

	env := newSAMEventEnv(t)
	deploySAM(t, env.client, samKafkaDocDBTemplate)

	ids := logicalIDs(t, env.client)
	assert.Equal(t, "AWS::Lambda::EventSourceMapping", ids["FnKafka"])
	assert.Equal(t, "AWS::Lambda::EventSourceMapping", ids["FnDocs"])

	bk, ok := env.backends.Lambda.Backend.(*lambdabackend.InMemoryBackend)
	require.True(t, ok)
	fn := env.fnName(t, "Fn")
	mappings := bk.ListEventSourceMappings(fn, "", "", 0).Data
	require.Len(t, mappings, 2)

	byTopics := map[bool]*lambdabackend.EventSourceMapping{}
	for _, m := range mappings {
		byTopics[len(m.Topics) > 0] = m
	}
	kafka := byTopics[true]
	assert.Equal(t, []string{"orders"}, kafka.Topics)
	assert.Equal(t, 50, kafka.BatchSize)
	assert.Len(t, kafka.SourceAccessConfigurations, 3)
	require.NotNil(t, kafka.SelfManagedEventSource)
	assert.ElementsMatch(t, []string{"broker1:9092", "broker2:9092"},
		kafka.SelfManagedEventSource.Endpoints["KAFKA_BOOTSTRAP_SERVERS"])
	require.NotNil(t, kafka.SelfManagedKafkaEventSourceConfig)
	assert.Equal(t, "group-1", kafka.SelfManagedKafkaEventSourceConfig.ConsumerGroupID)
	require.NotNil(t, kafka.FilterCriteria)
	assert.Len(t, kafka.FilterCriteria.Filters, 1)

	docs := byTopics[false]
	require.NotNil(t, docs.DocumentDBEventSourceConfig)
	assert.Equal(t, "shop", docs.DocumentDBEventSourceConfig.DatabaseName)
	assert.Equal(t, "orders", docs.DocumentDBEventSourceConfig.CollectionName)
	assert.Equal(t, "UpdateLookup", docs.DocumentDBEventSourceConfig.FullDocument)

	processed := getTemplate(t, env.client, types.TemplateStageProcessed)
	assert.Contains(t, processed, "s3:GetObject", "S3ReadPolicy template expanded into the role")
	assert.Contains(t, processed, "arn:${AWS::Partition}:iam::aws:policy/AmazonSQSFullAccess")
	assert.Contains(t, processed, "SelfManagedKafkaExecutionRolePolicy")
	assert.Contains(t, processed, "SamAutoGeneratedDocumentDBPolicy")

	assertDeleteClean(t, env.client)
}

