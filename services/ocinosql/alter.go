package ocinosql

import (
	"encoding/json"
	"strconv"
	"strings"

	"github.com/blackbirdworks/gopherstack/pkgs/strs"
)

// applyAlter applies an ALTER TABLE statement to t; t is untouched when it returns an error.
func (b *InMemoryBackend) applyAlter(t *Table, ddl string) *APIError {
	spec, aerr := parseAlter(ddl)
	if aerr != nil {
		return aerr
	}

	if !strs.Equal(spec.name, t.Name) {
		return errParam("ALTER TABLE names table '" + spec.name + "' but the request addresses '" + t.Name + "'")
	}

	cols := append([]Column{}, t.Columns...)

	var removed []string

	for _, d := range spec.drop {
		i := indexOfColumn(cols, d)
		if i < 0 {
			return errParam("cannot drop column '" + d + "': no such column")
		}

		if err := b.canDrop(t, cols[i].Name); err != nil {
			return err
		}

		removed = append(removed, cols[i].Name)
		cols = append(cols[:i], cols[i+1:]...)
	}

	var added []Column

	for _, c := range spec.add {
		if err := checkAddColumn(cols, c); err != nil {
			return err
		}

		cols, added = append(cols, c), append(added, c)
	}

	if spec.identity != nil && t.Identity != nil {
		return errParam("the table already has an identity column")
	}

	t.Columns = cols
	if spec.identity != nil {
		t.Identity = spec.identity
	}

	if spec.ttlHours != nil {
		t.TTLHours = *spec.ttlHours
	}

	for _, c := range removed {
		if t.Identity != nil && strs.Equal(t.Identity.Column, c) {
			t.Identity = nil
		}
	}

	reshapeRows(t, removed, added)
	t.DDL = renderDDL(t)

	return nil
}

func indexOfColumn(cols []Column, name string) int {
	for i, c := range cols {
		if strs.Equal(c.Name, name) {
			return i
		}
	}

	return -1
}

func (b *InMemoryBackend) canDrop(t *Table, col string) *APIError {
	if strs.ContainsFold(t.PrimaryKey, col) {
		return errParam("cannot drop primary key column '" + col + "'")
	}

	for _, ix := range t.Indexes {
		for _, k := range ix.Keys {
			if strs.Equal(k.Column, col) {
				return errParam("cannot drop column '" + col + "': it is used by index " + ix.Name)
			}
		}
	}

	return nil
}

func checkAddColumn(cols []Column, c Column) *APIError {
	if len(cols) >= maxColumns {
		return errLimit("a table can have at most " + strconv.Itoa(maxColumns) + " columns")
	}

	if indexOfColumn(cols, c.Name) >= 0 {
		return errParam("cannot add column '" + c.Name + "': it already exists")
	}

	ty, _ := parseTypeString(c.Type)
	if len(c.Default) > 0 {
		if _, msg := coerceDefault(ty, c.Default); msg != "" {
			return errParam("default of column '" + c.Name + "' " + msg)
		}
	}

	if c.NotNull && len(c.Default) == 0 && !c.Gen {
		return errParam("cannot add NOT NULL column '" + c.Name + "' without a DEFAULT")
	}

	return nil
}

func coerceDefault(ty *dtype, raw json.RawMessage) (any, string) {
	v, err := decodeJSON(raw)
	if err != nil {
		return nil, "is not a valid literal"
	}

	return coerce(ty, v)
}

// reshapeRows drops removed columns from stored rows and backfills defaults of added ones.
func reshapeRows(t *Table, removed []string, added []Column) {
	if len(removed) == 0 && len(added) == 0 {
		return
	}

	for _, r := range t.Rows {
		m := decodeRow(r.Value)

		for _, c := range removed {
			delete(m, c)
		}

		for _, c := range added {
			if len(c.Default) == 0 {
				continue
			}

			ty, _ := parseTypeString(c.Type)
			if v, msg := coerceDefault(ty, c.Default); msg == "" {
				m[c.Name] = v
			}
		}

		r.Value, _ = json.Marshal(m)
	}
}

func renderDDL(t *Table) string {
	parts := make([]string, 0, len(t.Columns)+1)

	for _, c := range t.Columns {
		s := c.Name + " " + c.Type

		switch {
		case t.Identity != nil && strs.Equal(t.Identity.Column, c.Name):
			s += renderIdentity(t.Identity)
		case c.AsUUID && c.Gen:
			s += " AS UUID GENERATED BY DEFAULT"
		case c.AsUUID:
			s += " AS UUID"
		}

		if c.NotNull && !strs.ContainsFold(t.PrimaryKey, c.Name) {
			s += " NOT NULL"
		}

		if len(c.Default) > 0 {
			s += " DEFAULT " + renderDefault(c.Default)
		}

		parts = append(parts, s)
	}

	pk := strings.Join(t.PrimaryKey[len(t.ShardKey):], ", ")
	if len(t.PrimaryKey) == len(t.ShardKey) {
		pk = ""
	}

	key := "SHARD(" + strings.Join(t.ShardKey, ", ") + ")"
	if pk != "" {
		key += ", " + pk
	}

	parts = append(parts, "PRIMARY KEY("+key+")")
	out := "CREATE TABLE " + t.Name + "(" + strings.Join(parts, ", ") + ")"

	if t.TTLHours > 0 {
		out += " USING TTL " + strconv.Itoa(t.TTLHours) + " HOURS"
	}

	return out
}

func renderIdentity(id *Identity) string {
	if id.Always {
		return " GENERATED ALWAYS AS IDENTITY"
	}

	if id.OnNull {
		return " GENERATED BY DEFAULT ON NULL AS IDENTITY"
	}

	return " GENERATED BY DEFAULT AS IDENTITY"
}

func renderDefault(raw json.RawMessage) string {
	var s string
	if json.Unmarshal(raw, &s) == nil {
		return "'" + strings.ReplaceAll(s, "'", "''") + "'"
	}

	return string(raw)
}
