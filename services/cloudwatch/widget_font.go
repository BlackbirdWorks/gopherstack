package cloudwatch

import "strings"

// The 3x5 label font is stored as two const strings rather than a package-level
// map or a large switch: glyphChars lists the supported runes in order, and
// glyphData holds glyphH bytes per rune (the row bitmaps, low 3 bits, MSB
// leftmost). This keeps the font allocation-free, global-variable-free, and of low
// cyclomatic complexity.
const glyphChars = " .,-+:/%()#0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ"

const glyphData = "" +
	"\x00\x00\x00\x00\x00\x00\x00\x00\x00\x02\x00\x00\x00\x02\x04\x00\x00\x07\x00\x00\x00\x02\x07\x02\x00" +
	"\x00\x02\x00\x02\x00\x01\x01\x02\x04\x04\x05\x01\x02\x04\x05\x01\x02\x02\x02\x01\x04\x02\x02\x02\x04" +
	"\x05\x07\x05\x07\x05\x07\x05\x05\x05\x07\x02\x06\x02\x02\x07\x07\x01\x07\x04\x07\x07\x01\x07\x01\x07" +
	"\x05\x05\x07\x01\x01\x07\x04\x07\x01\x07\x07\x04\x07\x05\x07\x07\x01\x02\x02\x02\x07\x05\x07\x05\x07" +
	"\x07\x05\x07\x01\x07\x02\x05\x07\x05\x05\x06\x05\x06\x05\x06\x03\x04\x04\x04\x03\x06\x05\x05\x05\x06" +
	"\x07\x04\x06\x04\x07\x07\x04\x06\x04\x04\x03\x04\x05\x05\x03\x05\x05\x07\x05\x05\x07\x02\x02\x02\x07" +
	"\x01\x01\x01\x05\x02\x05\x05\x06\x05\x05\x04\x04\x04\x04\x07\x05\x07\x07\x05\x05\x05\x07\x07\x07\x05" +
	"\x02\x05\x05\x05\x02\x06\x05\x06\x04\x04\x02\x05\x05\x03\x01\x06\x05\x06\x05\x05\x03\x04\x02\x01\x06" +
	"\x07\x02\x02\x02\x02\x05\x05\x05\x05\x07\x05\x05\x05\x05\x02\x05\x05\x07\x07\x05\x05\x05\x02\x05\x05" +
	"\x05\x05\x02\x02\x02\x07\x01\x02\x04\x07"

// glyph3x5 returns the 3x5 bitmap for a rune used to label the rendered metric
// widget. The second result is false for runes with no glyph (callers fall back to
// the '#' box).
func glyph3x5(r rune) ([glyphH]byte, bool) {
	idx := strings.IndexRune(glyphChars, r)
	if idx < 0 {
		return [glyphH]byte{}, false
	}

	var out [glyphH]byte
	off := idx * glyphH
	for i := range glyphH {
		out[i] = glyphData[off+i]
	}

	return out, true
}
