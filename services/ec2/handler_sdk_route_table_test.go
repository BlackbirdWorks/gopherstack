// sdkRouteCases is the authoritative Action value for every real EC2
// operation, extracted from ec2@v1.319.1 serializers.go: each op's
// awsEc2query_serializeOp<Op>.HandleSerialize sets
// body.Key("Action").String("<Op>") and always POSTs to "/" -- EC2 is
// EC2-Query/XML (services/_PROTOCOLS.md), so unlike a REST-family service
// there is no path template to get wrong: dispatch is entirely by this one
// form field, via h.ops[action] map lookup (handler.go:618). ExtractOperation
// reads r.Form.Get("Action") directly, so the class of bug this table
// catches is a dispatch-table key that doesn't exactly match the real op
// name (typo, wrong case) -- not a route-template mismatch. EC2-Query is
// case-insensitive for XML field names on the wire, but gopherstack's own
// dispatch is a Go string map, which is always exact-match regardless of
// protocol.
//
// This table covers all 785 real EC2 ops (ec2@v1.319.1) -- the pinned
// SDK's largest operation set in this repo. Confirmed by diffing h.ops's
// 785 map keys (built across buildCoreOps's map literal, one
// maps.Copy(ops, ...) block in registerSnapshotsOps, and every other
// registerXOps's ops["Name"] = ... assignments) against this exact list:
// zero mismatches in either direction, both ways clean at EC2's full scale.
