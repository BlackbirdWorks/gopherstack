func sslCipherGroups() [][]string {
	blocks := strings.Split(strings.TrimSpace(sslCipherGroupData), "---")
	out := make([][]string, 0, len(blocks))

	for _, b := range blocks {
		out = append(out, strings.Fields(b))
	}

	return out
}

func sslPolicySpecs() []sslPolicySpec {
	lines := strings.Fields(sslPolicyData)
	out := make([]sslPolicySpec, 0, len(lines))

	for _, line := range lines {
		parts := strings.Split(line, "|")
		group, _ := strconv.Atoi(parts[3])
		out = append(out, sslPolicySpec{
			name:      parts[0],
			protocols: strings.Split(parts[1], ","),
			types:     strings.Split(parts[2], ","),
			ciphers:   group,
		})
	}

	return out
}
